/* Structure of Linked List Node
class Node {
    int data;
    Node next;

    Node(int x) {
        data = x;
        next = null;
    }
}
*/

class Solution {
    Node reverseList(Node head) {
        // code here
        if(head == null || head.next == null){
            return head;
        }

        Node temp = reverseList(head.next);

        head.next.next = head;
        head.next = null;
        return temp;
        
    }
}

