class Solution {
    public ArrayList<Integer> printList(Node head) {
        // code here
        ArrayList<Integer> result = new ArrayList<>();
        Node curr = head;
        
        if(head.next == null){
            return new ArrayList<>();
        }
        
        
        while(curr != null){
            result.add(curr.data);
            curr = curr.next;
        }
        
        return result;
    }
}

